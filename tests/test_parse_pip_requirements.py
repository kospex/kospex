"""parse_pip_requirements_file must read pip's logical lines (#247).

pip-compile --generate-hashes writes one entry per logical line (requirement,
then one ``--hash=`` row, each continued with a trailing backslash), and hand
written files use inline comments. The line-by-line reader dropped all of
them; the parser now joins continuations, strips per-requirement options and
handles ``#`` comments the way pip does.

Only the pure parsing path is needed here, so modules the parser never
touches are stubbed when the real import fails; in a full dev environment the
real modules load untouched.
"""
import importlib
import sys
import types

import pytest


def _import_or_stub(name, attrs):
    try:
        importlib.import_module(name)
    except ImportError:
        module = types.ModuleType(name)
        for attr in attrs:
            setattr(module, attr, object)
        sys.modules[name] = module


def _kd():
    sys.path.insert(0, "src")
    _import_or_stub("sqlite_utils", ["Database"])
    _import_or_stub("prettytable", ["PrettyTable"])
    _import_or_stub("dotenv", ["load_dotenv"])
    _import_or_stub("panopticas", [])
    import kospex_dependencies

    return kospex_dependencies.KospexDependencies


PIPCOMPILE_LOCK = (
    "#\n"
    "# This file is autogenerated by pip-compile\n"
    "absl-py==2.1.0 \\\n"
    "    --hash=sha256:bf25b2c2eed013ca456918c453d687eab4e8309fba81ee2f4c1a6aa2494175eb \\\n"
    "    --hash=sha256:e5797bc6abe45f64fd95dc06394ca3f2bedf3b5d895e9da691c9ee3397d70092\n"
    "requests==2.31.0  # pin for CVE-2024-35195\n"
    "h5py ~= 3.10.0  # Earliest version for Python 3.12\n"
    "--index-url https://example.com/simple\n"
    "\n"
    "# a comment line\n"
    "unpinned-package\n"
)


def _names(parsed):
    return [r["package_name"] for r in parsed]


def test_pip_compile_continuations_are_parsed(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text(PIPCOMPILE_LOCK)
    parsed = _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    names = _names(parsed)
    assert "absl-py" in names
    assert "requests" in names
    assert "h5py" in names
    assert "unpinned-package" in names


def test_hash_rows_do_not_become_packages(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text(PIPCOMPILE_LOCK)
    parsed = _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    assert _names(parsed).count("absl-py") == 1
    assert not any("sha256" in str(r) for r in parsed)


def test_continuation_entry_keeps_version(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text(PIPCOMPILE_LOCK)
    parsed = {
        r["package_name"]: r["package_version"]
        for r in _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    }
    assert parsed["absl-py"] == "==2.1.0"
    assert parsed["requests"] == "==2.31.0"
    assert parsed["h5py"] == "~=3.10.0"


def test_file_level_option_lines_stay_ignored(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text("--index-url https://example.com/simple\nrequests==2.31.0\n")
    parsed = _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    assert _names(parsed) == ["requests"]


def test_hash_fragment_in_direct_url_is_not_a_comment(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text("name @ https://example.com/pkg-1.0.tar.gz#egg=name\n")
    parsed = _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    assert _names(parsed) == ["name"]


def test_vcs_directive_stays_ignored(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text("-e .\n-r other.txt\nrequests==2.31.0\n")
    parsed = _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    assert _names(parsed) == ["requests"]


def test_unterminated_continuation_yields_the_partial_line(tmp_path):
    # pip's own join_lines yields the dangling buffer, so a file ending in a
    # backslash keeps its partial line rather than crashing or vanishing.
    path = tmp_path / "requirements.txt"
    path.write_text("absl-py==2.1.0 \\\n")
    parsed = _kd().__new__(_kd()).parse_pip_requirements_file(str(path))
    assert _names(parsed) == ["absl-py"]
